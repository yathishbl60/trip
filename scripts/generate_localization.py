"""Generate typed shared accessors from the single TripLocalization catalog."""
import argparse
import collections
import json
import re
from pathlib import Path
from architecture.localization_resources import extraction_artifact, native_keys

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "Packages/TripKit/Sources/TripLocalization"
CATALOG = DESTINATION / "Resources/Localizable.xcstrings"


def accessor(key, entry):
    metadata = dict(line[1:].split(" ", 1) for line in entry["comment"].splitlines() if line.startswith("@"))
    symbol = metadata["symbol"]
    parameters = [value for value in metadata["parameters"].split(",") if value]
    if not parameters:
        return metadata["group"], [f'    public static var {symbol}: TripText {{', f'        TripText("{key}")', '    }', '']
    declaration = ", ".join(f"_ value{index}: {kind}" for index, kind in enumerate(parameters, 1))
    value = "".join(f"\\(value{index})" for index in range(1, len(parameters) + 1))
    return metadata["group"], [f"    public static func {symbol}({declaration}) -> TripText {{",
                               f'        TripText("{key}", value: "{value}")', '    }', '']


def generate():
    groups = collections.defaultdict(list)
    for key, entry in sorted(json.loads(CATALOG.read_text())["strings"].items()):
        if "@symbol " not in entry.get("comment", ""):
            continue
        group, lines = accessor(key, entry)
        groups[group].append(lines)
    result = {}
    for group, accessors in groups.items():
        for offset in range(0, len(accessors), 22):
            suffix = "" if offset == 0 else str(offset // 22 + 1)
            lines = ['// Generated by scripts/generate_localization.py. Edit the String Catalog.',
                     'import Foundation', '', 'public nonisolated extension TripText {']
            lines += [line.replace("    public static", "    static") for item in accessors[offset:offset + 22] for line in item]
            lines += ['}', '']
            result[DESTINATION / f"TripText+{group}{suffix}.swift"] = "\n".join(lines)
    catalog = json.loads(CATALOG.read_text())
    metadata_keys = {key for _, key, table in native_keys(ROOT) if table == "Localizable"}
    missing = metadata_keys - catalog["strings"].keys()
    if missing:
        raise ValueError(f"Add native metadata translations to {CATALOG}: {sorted(missing)}")
    catalog["strings"] = {key: dict(catalog["strings"][key], extractionState="manual") for key in metadata_keys}
    host = DESTINATION / "HostResources/Localizable.xcstrings"
    if host.exists():
        extracted = json.loads(host.read_text())["strings"]
        catalog["strings"].update({key: entry for key, entry in extracted.items()
                                   if key not in metadata_keys and extraction_artifact(key, entry)})
    result[host] = json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    manifest = ROOT / "Performance/sources.txt"
    marker = "# Shared text used by production projections and presentation checks."
    base = manifest.read_text().split(marker)[0].rstrip()
    sources = sorted(str(path.relative_to(ROOT)) for path in result if path.suffix == ".swift")
    sources.append(str((DESTINATION / "TripText.swift").relative_to(ROOT)))
    result[manifest] = base + "\n\n" + marker + "\n" + "\n".join(sorted(sources)) + "\n"
    project = ROOT / "trip.xcodeproj/project.pbxproj"
    privacy = json.loads((DESTINATION / "HostResources/InfoPlist.xcstrings").read_text())
    fallback = privacy["strings"]["NSLocationWhenInUseUsageDescription"]["localizations"]["en"]["stringUnit"]["value"]
    result[project] = re.sub(r'(INFOPLIST_KEY_NSLocationWhenInUseUsageDescription = )"(?:\\.|[^"\\])*";',
                             lambda match: match[1] + json.dumps(fallback, ensure_ascii=False) + ";", project.read_text())
    return result


def is_current(path, expected):
    if not path.exists():
        return False
    actual = path.read_text()
    if path.suffix == ".xcstrings":
        return json.loads(actual) == json.loads(expected)
    return actual == expected


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate()
    stale = [path for path, text in outputs.items() if not is_current(path, text)]
    obsolete = set(DESTINATION.glob("TripText+*.swift")) - set(outputs)
    if args.check:
        if stale or obsolete:
            raise SystemExit("Localization accessors are stale. Run python3 scripts/generate_localization.py")
        print(f"Checked {len(outputs)} generated localization artifacts.")
    else:
        for path in stale:
            path.write_text(outputs[path])
        for path in obsolete:
            path.unlink()
        print(f"Updated {len(stale)} of {len(outputs)} localization artifacts; removed {len(obsolete)} obsolete files.")
