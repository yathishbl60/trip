"""Check native metadata lookups and catalog membership without compiling targets."""
import json
import re
import subprocess


def extraction_artifact(key, entry):
    """Recognize Xcode-owned interpolation/separator entries, never authored copy."""
    if not entry.get("isCommentAutoGenerated") or entry.get("extractionState") == "manual":
        return False
    if "@symbol " in entry.get("comment", "") or not format_scaffolding(key):
        return False
    return all(format_scaffolding(unit["value"]) for unit in string_units(entry.get("localizations", {})))


def format_scaffolding(value):
    stripped = re.sub(r"%(?:(?:\d+)\$)?(?:@|lld)", "", value)
    return not any(character.isalnum() for character in stripped)


def string_units(value):
    if "stringUnit" in value:
        yield value["stringUnit"]
    else:
        for child in value.values():
            if isinstance(child, dict):
                yield from string_units(child)


def check_resources(root, destination):
    output = subprocess.check_output(["plutil", "-convert", "json", "-o", "-",
                                     str(root / "trip.xcodeproj/project.pbxproj")], text=True)
    objects = json.loads(output)["objects"]
    targets = {item["name"]: item for item in objects.values() if item.get("isa") == "PBXNativeTarget"}
    host = str((destination / "HostResources").relative_to(root))
    required = {"trip": {"Localizable", "AppShortcuts", "InfoPlist"}, "TripWidgets": {"Localizable"}}
    for name, catalogs in required.items():
        phases = [objects[item] for item in targets[name]["buildPhases"]]
        references = [objects[item]["fileRef"] for phase in phases if phase["isa"] == "PBXResourcesBuildPhase"
                      for item in phase.get("files", [])]
        paths = {objects[reference]["path"] for reference in references}
        assert {f"{host}/{catalog}.xcstrings" for catalog in catalogs} <= paths, (name, "Catalog membership")
    project = next(item for item in objects.values() if item.get("isa") == "PBXProject")
    assert {"en", "hi", "kn"} <= set(project["knownRegions"]), "Missing project languages"
    manifest = (root / "Packages/TripKit/Package.swift").read_text()
    assert 'defaultLocalization: "en"' in manifest and '.process("Resources")' in manifest


def native_keys(root):
    """Yield the bundle table and literal key required by native metadata."""
    patterns = [r'@(?:Parameter|Property|ComputedProperty|DeferredProperty)\(title: "([^"]+)"',
                r'@(?:Parameter|Property|ComputedProperty|DeferredProperty)\([^)]*?\bdescription: "([^"]+)"',
                r'(?:IntentDescription|TypeDisplayRepresentation)\((?:name: )?"([^"]+)"',
                r'DisplayRepresentation\(title: "([^"]+)"', r'shortTitle: "([^"]+)"',
                r'\.(?:displayName|configurationDisplayName|description)\("([^"]+)"',
                r'static var title: LocalizedStringResource \{ "([^"]+)"']
    roots = [root / "trip/App/Intents", root / "trip/Shared/System", root / "TripWidgets"]
    for area in roots:
        for path in area.rglob("*.swift"):
            source = path.read_text()
            for pattern in patterns:
                for key in re.findall(pattern, source):
                    if "\\(" in key:
                        continue
                    yield path, key, "Localizable"
            for match in re.finditer(r'(Summary\(|phrases: \[)"((?:\\.|[^"\\])*)"', source):
                key = re.sub(r'\\\((.*?)\)', token, match[2])
                yield path, key, "AppShortcuts" if match[1].startswith("phrases") else "Localizable"


def check_native_keys(root, catalog, shortcuts):
    catalog = {key: entry for key, entry in catalog.items() if not extraction_artifact(key, entry)}
    assert all(entry.get("extractionState") == "manual" for entry in catalog.values()), "Generated metadata must be manually managed"
    tables = {"Localizable": catalog, "AppShortcuts": shortcuts}
    referenced = set()
    for path, key, table in native_keys(root):
        assert key in tables[table], (path, key, "Missing native metadata translation")
        if table == "Localizable":
            referenced.add(key)
    assert set(catalog) == referenced, (set(catalog) - referenced, "Unused generated native metadata")


def token(match):
    expression = match[1]
    name = "applicationName" if expression == ".applicationName" else re.search(r'\.\$(\w+)', expression)[1]
    return "${" + name + "}"
